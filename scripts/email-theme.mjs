/**
 * Converts the app's daisyUI theme into values HTML email can use.
 *
 * Email clients don't support CSS variables or `oklch()` colors, so the email can't read the
 * theme the way the app does. This script reads the same theme the stylesheet uses and writes
 * its colors as hex and its corner sizes as pixels to `app/email/theme.generated.ts`.
 * `test/email-theme.test.ts` fails if that file no longer matches the theme.
 *
 * Run with `npm run email:theme` after changing the theme in `styles/app.css`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { transform } from 'lightningcss'

/** The light theme the app uses (`styles/app.css`). Email is light only: Gmail ignores dark mode. */
const THEME_NAME = 'winter'
const THEME_FILE = fileURLToPath(new URL(`../node_modules/daisyui/theme/${THEME_NAME}.css`, import.meta.url))
/** Where the app changes a few of the theme's values (`@plugin 'daisyui/theme' { name: 'winter'; ... }`). */
const APP_STYLES = fileURLToPath(new URL('../styles/app.css', import.meta.url))
const OUTPUT_FILE = fileURLToPath(new URL('../app/email/theme.generated.ts', import.meta.url))

/** Share of the text color in secondary text, matching the app's `text-base-content/80`. */
const MUTED_SHARE = 0.8

/**
 * Reads the theme and returns the email's tokens.
 * @returns colors as 6-digit hex strings and corner sizes in pixels
 */
export function buildEmailTheme() {
  // The built-in theme first, then the app's own changes to it, so a later value wins.
  const overrides = [
    ...readFileSync(APP_STYLES, 'utf8').matchAll(/@plugin\s+['"]daisyui\/theme['"]\s*\{([^}]*)\}/g),
  ]
    .map(([, body]) => body)
    .filter((body) => new RegExp(`name:\\s*['"]${THEME_NAME}['"]`).test(body))
  const source = [readFileSync(THEME_FILE, 'utf8'), ...overrides].join('\n')

  // Step 1: pull each `--color-*` value out and let Lightning CSS lower oklch() to hex by
  // targeting a browser old enough to need the fallback.
  const declarations = [...source.matchAll(/--color-([a-z0-9-]+):\s*(oklch\([^)]*\))/g)]
  const lowered = transform({
    filename: 'theme.css',
    code: Buffer.from(declarations.map(([, name, value]) => `.${name}{color:${value}}`).join('\n')),
    targets: { ie: 11 << 16 },
  }).code.toString()
  const colors = Object.fromEntries(
    [...lowered.matchAll(/\.([a-z0-9-]+)\s*\{\s*color:\s*(#[0-9a-f]{3,6})/g)].map(([, name, hex]) => [
      name,
      sixDigit(hex),
    ]),
  )

  // Step 2: corner sizes, from rem to pixels (1rem = 16px).
  const radius = (name) => {
    const found = [...source.matchAll(new RegExp(`--radius-${name}:\\s*([0-9.]+)rem`, 'g'))].at(-1)
    if (!found) throw new Error(`The theme has no --radius-${name}`)
    return Math.round(Number(found[1]) * 16)
  }

  const required = [
    'base-100',
    'base-200',
    'base-300',
    'base-content',
    'primary',
    'primary-content',
    'neutral',
    'neutral-content',
  ]
  for (const name of required) {
    if (!colors[name]) throw new Error(`The theme has no --color-${name}`)
  }

  return {
    page: colors['base-200'],
    surface: colors['base-100'],
    border: colors['base-300'],
    text: colors['base-content'],
    // Secondary text: the text color mixed toward the surface, as the app does with opacity.
    muted: mix(colors['base-content'], colors['base-100'], MUTED_SHARE),
    primary: colors.primary,
    primaryText: colors['primary-content'],
    neutral: colors.neutral,
    neutralText: colors['neutral-content'],
    radiusBox: radius('box'),
    radiusField: radius('field'),
  }
}

/** Expands a 3-digit hex color to 6 digits; leaves a 6-digit one alone. */
function sixDigit(hex) {
  if (hex.length !== 4) return hex
  return `#${hex
    .slice(1)
    .split('')
    .map((digit) => digit + digit)
    .join('')}`
}

/**
 * One color channel of a 6-digit hex color.
 * @param index 0 for red, 1 for green, 2 for blue
 * @returns 0 to 255
 */
function channel(hex, index) {
  return Number.parseInt(hex.slice(1 + index * 2, 3 + index * 2), 16)
}

/**
 * Mixes two hex colors in sRGB.
 * @param share how much of `first` to keep, from 0 to 1
 */
function mix(first, second, share) {
  const mixed = [0, 1, 2].map((index) =>
    Math.round(channel(first, index) * share + channel(second, index) * (1 - share)),
  )
  return `#${mixed.map((value) => value.toString(16).padStart(2, '0')).join('')}`
}

/** The generated module's text for a set of tokens. */
export function emailThemeModule(theme) {
  return `// Generated by scripts/email-theme.mjs from the daisyUI theme. Do not edit by hand:
// change the theme in styles/app.css, then run \`npm run email:theme\`.

/** The app's theme as values HTML email can use: hex colors and pixel corner sizes. */
export const emailTheme = ${JSON.stringify(theme, null, 2)
    .replace(/"([a-zA-Z]+)":/g, '$1:')
    .replace(/"/g, "'")} as const

export type EmailTheme = typeof emailTheme
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT_FILE, emailThemeModule(buildEmailTheme()))
  console.log(`Wrote ${OUTPUT_FILE}`)
}
